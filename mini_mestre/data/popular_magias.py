# Observação de conferência:
# Na lista de Feiticeiro, "Escuridão" aparece como transmutação no texto
# extraído da lista de classe, mas a descrição da própria magia no mesmo livro
# a identifica como "2º nível de evocação". O catálogo usa "evocação".


def _catalogo_unico():
    catalogo = {}

    for niveis in LISTAS_MAGIAS.values():
        for nivel, magias in niveis.items():
            for nome, escola, ritual in magias:
                chave = nome.casefold()

                if chave in catalogo:
                    anterior = catalogo[chave]

                    if (
                        anterior["nivel"] != nivel
                        or anterior["escola"] != escola
                        or anterior["ritual"] != ritual
                    ):
                        raise ValueError(
                            "Conflito de dados para a magia "
                            f"{nome}: {anterior} x "
                            f"{{'nivel': {nivel}, 'escola': '{escola}', "
                            f"'ritual': {ritual}}}"
                        )

                else:
                    catalogo[chave] = {
                        "nome": nome,
                        "nivel": nivel,
                        "escola": escola,
                        "ritual": ritual,
                    }

    return list(catalogo.values())


